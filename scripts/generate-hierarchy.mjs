import fs from 'fs';
import * as topojson from 'topojson-client';
import { geoBounds } from 'd3-geo';

const data = JSON.parse(fs.readFileSync('./public/geo/india-districts.json', 'utf8'));
const features = topojson.feature(data, data.objects.DISTRICT_BOUNDARY).features;

const stateMap = new Map();

features.forEach(f => {
  const stateName = f.properties.STATE_UT;
  if (!stateName) return;
  const districtName = f.properties.DISTRICT;
  if (!districtName) return;
  
  if (!stateMap.has(stateName)) {
    stateMap.set(stateName, []);
  }
  stateMap.get(stateName).push({ districtName, feature: f });
});

function toSlug(str) {
  return str.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
}

const statesData = [];

for (const [stateName, districts] of stateMap.entries()) {
  const stateSlug = toSlug(stateName);
  const districtFeatures = districts.map(d => d.feature);
  const fc = { type: 'FeatureCollection', features: districtFeatures };
  const bounds = geoBounds(fc);
  
  const center = [
    (bounds[0][0] + bounds[1][0]) / 2,
    (bounds[0][1] + bounds[1][1]) / 2
  ];
  
  const widthDeg = bounds[1][0] - bounds[0][0];
  const heightDeg = bounds[1][1] - bounds[0][1];
  
  // Padding factor to ensure it fits nicely in the SVG
  const zoom = Math.max(1, Math.min(22 / widthDeg, 22 / heightDeg));
  
  // Create a unique set of districts, eliminating duplicates by ID (sometimes shapefiles have multiple polygons per district)
  const uniqueDistricts = new Map();
  districts.forEach(d => {
    const slug = toSlug(d.districtName);
    if (!uniqueDistricts.has(slug)) {
      uniqueDistricts.set(slug, {
        districtId: `${stateSlug}-${slug}`,
        districtName: d.districtName,
        isCoastal: false
      });
    }
  });
  
  statesData.push({
    stateId: stateSlug,
    stateName: stateName,
    isCoastal: false,
    center,
    zoom,
    districts: Array.from(uniqueDistricts.values())
  });
}

const tsContent = `// AUTO-GENERATED FILE
// Generated by scripts/generate-hierarchy.mjs

export interface StateInfo {
  stateId: string;
  stateName: string;
  isCoastal: boolean;
  center: [number, number];
  zoom: number;
  districts: { districtId: string; districtName: string; isCoastal: boolean }[];
}

export const STATES_DATA: StateInfo[] = ${JSON.stringify(statesData, null, 2)};
`;

fs.writeFileSync('./src/lib/stateHierarchy.ts', tsContent);
console.log('Generated src/lib/stateHierarchy.ts successfully!');
